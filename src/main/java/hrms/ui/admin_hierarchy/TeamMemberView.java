    /** Read-only member list of the team with {@code teamId}. */
    public TeamMemberView(java.awt.Frame parent, boolean modal, long teamId, String teamName) {
        super(parent, modal);
        initComponents();
        this.teamId = teamId;
        setTitle("View Team Members");
        labelTeamName.setText(teamName == null ? "" : teamName);
        labelCount.setText(""); // filled once the load completes
        setupTable();
        setupActions();
        loadMembers();
    }

    private void setupTable() {
        // Columns must match TeamMember.toTableRow(): ID, Staff, Team, Parent,
        // Remark, Created By, Created Date. The Team column (2) is hidden
        // because this dialog already shows one team. No context menu and no
        // double-click handler — the dialog is view-only.
        table = HrmsTable.builder(
                "ID", "Staff", "Team", "Parent", "Remark", "Created By", "Created Date")
                .hiddenColumn(0)
                .hiddenColumn(2)
                .fixedColumn(1, 220)
                .fixedColumn(3, 180)
                .fixedColumn(4, 170)
                .fixedColumn(5, 110)
                .fixedColumn(6, 130)
                .columnType(6, java.time.LocalDateTime.class)
                .build();
        jScrollPane1.setViewportView(table);
    }

    private void setupActions() {
        // The form's GEN block has no event handlers, so the button is wired here.
        btnClose.addActionListener(e -> dispose());
    }

    private void loadMembers() {
        UiThread.executeAsync("Load team members",
                () -> TeamMemberRepository.searchAsTableRows(null, teamId),
                rows -> {
                    // Restore the table in case a previous load failed and showed ErrorPanel.
                    jScrollPane1.setViewportView(table);
                    table.setRows(rows);
                    labelCount.setText(rows.size()
                            + (rows.size() == 1 ? " active member" : " active members"));
                },
                ex -> showLoadError(ex, this::loadMembers,
                        "Cannot load the team members."));
    }

    /**
     * Swaps the table area for an inline error state with retry (details go to
     * the log).
     */
    private void showLoadError(Exception ex, Runnable retry, String message) {
        LOG.warn("Team member view load failed", ex);
        jScrollPane1.setViewportView(new ErrorPanel(
                message + " Check that the database is running, then try again.", retry));
    }

