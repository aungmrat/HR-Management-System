  /** Create when {@code existing} is null; edit when non-null. */
  public DepartmentDialog(java.awt.Frame parent, boolean modal, Department existing) {
    super(parent, modal);
    initComponents();
    this.editing = existing;
    if (existing == null) {
      setTitle("New Department");
    } else {
      setTitle("Edit Department");
      prefill(existing);
    }
    setupActions();
  }

  private void prefill(Department department) {
    textCode.setText(department.getCode());
    textName.setText(department.getName());
    textAddress.setText(department.getAddress() == null ? "" : department.getAddress());
    if (department.getStatus() != null && !department.getStatus().isBlank()) {
      ComboStatus.setSelectedItem(department.getStatus());
    }
    textRemark.setText(department.getRemark() == null ? "" : department.getRemark());
  }

  private void setupActions() {
    btnCancel.addActionListener(e -> dispose());
    btnSave.addActionListener(e -> {
      try {
        saveAndClose();
      } catch (AuthorizationException ex) {
        ErrorHandler.handle(this, ex);
      }
    });
  }

  /** Permission gate for Save; static so headless tests can verify it. */
  static void requireSavePermission(boolean isEdit) {
    SecurityService.require(isEdit
            ? Permissions.DEPARTMENT_UPDATE : Permissions.DEPARTMENT_CREATE);
  }

  private void saveAndClose() {
    try {
      requireSavePermission(editing != null);
      String code = textCode.getText();
      String name = textName.getText();
      String address = textAddress.getText();
      String status = ComboStatus.getSelectedItem() == null
              ? "Active" : ComboStatus.getSelectedItem().toString().trim();
      String remark = textRemark.getText();

      java.util.List<String> errors = new java.util.ArrayList<>();
      if (code == null || code.isBlank()) {
        errors.add("Code is required.");
      } else if (code.trim().length() > 10) {
        errors.add("Code must be at most 10 characters.");
      }
      if (name == null || name.isBlank()) {
        errors.add("Department name is required.");
      } else if (name.trim().length() > 100) {
        errors.add("Department name must be at most 100 characters.");
      }
      if (!errors.isEmpty()) {
        throw new ValidationException(errors);
      }

      Long userId = SessionContext.isAuthenticated() ? SessionContext.currentUserId() : null;
      boolean isEdit = editing != null;
      Department department;
      if (isEdit) {
        department = editing;
        department.setCode(code.trim());
        department.setName(name.trim());
        department.setAddress(address);
        department.setStatus(status);
        department.setRemark(remark);
        department.setModifiedBy(userId);
      } else {
        department = Department.create(code.trim(), name.trim(), address, status, remark, userId);
      }

      btnSave.setEnabled(false);
      UiThread.executeAsync(isEdit ? "Update department" : "Save department",
              () -> isEdit
                      ? DepartmentRepository.update(department)
                      : DepartmentRepository.insert(department),
              result -> {
                if (isEdit) {
                  LOG.info("Department updated id={}", department.getId());
                } else {
                  LOG.info("Department saved with id {}", result);
                }
                dispose();
              },
              error -> {
                btnSave.setEnabled(true);
                ErrorHandler.handle(this, error);
              });
    } catch (ValidationException e) {
      ErrorHandler.handle(this, e);
    }
  }

